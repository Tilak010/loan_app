import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:provider/provider.dart';
import 'package:diksha_finance/config/app_routes.dart';
import 'package:diksha_finance/config/app_theme.dart';
import 'package:diksha_finance/providers/app_provider.dart';
import 'package:diksha_finance/providers/loan_provider.dart';
import 'package:diksha_finance/screens/loan_apply/loan_status_screen.dart';
import 'package:diksha_finance/widgets/app_scaffold.dart';

void main() {
  group('Screen 9: LoanStatusScreen Tests', () {
    setUp(() {
      final binding = TestWidgetsFlutterBinding.ensureInitialized();
      binding.platformDispatcher.views.first.physicalSize =
          const Size(1080, 2400);
      binding.platformDispatcher.views.first.devicePixelRatio = 2.0;
    });

    tearDown(() {
      final binding = TestWidgetsFlutterBinding.ensureInitialized();
      binding.platformDispatcher.views.first.resetPhysicalSize();
      binding.platformDispatcher.views.first.resetDevicePixelRatio();
    });

    Widget createLoanStatusApp({LoanProvider? customLoanProvider}) {
      return MultiProvider(
        providers: [
          ChangeNotifierProvider(create: (_) => customLoanProvider ?? LoanProvider()),
          ChangeNotifierProvider(create: (_) => AppProvider()),
        ],
        child: MaterialApp(
          theme: AppTheme.lightTheme,
          routes: {
            AppRoutes.loanStatus: (ctx) => const LoanStatusScreen(),
            AppRoutes.home: (ctx) => const AppScaffold(),
          },
          home: const LoanStatusScreen(),
        ),
      );
    }

    testWidgets('Renders all required Screen 9 headings, status badge, and parameters',
        (WidgetTester tester) async {
      final loanProvider = LoanProvider();
      loanProvider.setLoanType('Personal Loan');
      loanProvider.setLoanAmount(50000);
      loanProvider.setTenureMonths(12);
      loanProvider.setIllustrativeRate(24.0);

      await tester.pumpWidget(createLoanStatusApp(customLoanProvider: loanProvider));
      await tester.pumpAndSettle();

      // 1. Heading
      expect(find.text('Demo Application Completed'), findsOneWidget);

      // 2. Status Badge with exact text
      expect(
        find.text('SIMULATED APPROVAL — NOT A REAL LOAN APPROVAL'),
        findsOneWidget,
      );

      // 3. Demo Application Reference Number
      expect(find.text('Demo Application Ref. No.'), findsOneWidget);
      expect(find.text(loanProvider.demoReferenceNumber), findsOneWidget);

      // 4. Selected loan type
      expect(find.text('Personal Loan'), findsOneWidget);

      // 5. Selected loan amount
      expect(find.text('₹50,000'), findsOneWidget);

      // 6. Selected tenure
      expect(find.text('12 Months'), findsOneWidget);

      // 7. Illustrative EMI
      expect(find.textContaining('/ mo'), findsOneWidget);

      // 8. Device date
      expect(find.text('Date Generated by Device'), findsOneWidget);

      // 9. Non-disbursement notice
      expect(find.text('NBFC Demonstration Notice'), findsOneWidget);
      expect(
        find.textContaining('Disbursement is not scheduled'),
        findsOneWidget,
      );

      // 10. Buttons
      expect(find.text('View Loan Details'), findsOneWidget);
      expect(find.text('Back to Home'), findsOneWidget);
    });

    testWidgets('Tapping View Loan Details opens My Loan Details bottom sheet',
        (WidgetTester tester) async {
      final loanProvider = LoanProvider();
      loanProvider.setLoanType('Business Loan');
      loanProvider.setLoanAmount(100000);
      loanProvider.setTenureMonths(6);

      await tester.pumpWidget(createLoanStatusApp(customLoanProvider: loanProvider));
      await tester.pumpAndSettle();

      // Tap "View Loan Details"
      final viewDetailsBtn = find.text('View Loan Details');
      await tester.ensureVisible(viewDetailsBtn);
      await tester.tap(viewDetailsBtn);
      await tester.pumpAndSettle();

      // Should open bottom sheet with My Loan Details
      expect(find.text('My Loan Details'), findsOneWidget);
      expect(find.text('Close Details'), findsOneWidget);
      expect(find.text('Business Loan'), findsWidgets);

      // Tap Close Details
      await tester.tap(find.text('Close Details'));
      await tester.pumpAndSettle();

      // Bottom sheet dismissed
      expect(find.text('Close Details'), findsNothing);
    });

    testWidgets('Tapping Back to Home returns to dashboard AppScaffold',
        (WidgetTester tester) async {
      await tester.pumpWidget(createLoanStatusApp());
      await tester.pumpAndSettle();

      final backToHomeBtn = find.text('Back to Home');
      await tester.ensureVisible(backToHomeBtn);
      await tester.tap(backToHomeBtn);
      await tester.pumpAndSettle();

      // Returns to AppScaffold / Dashboard
      expect(find.byType(AppScaffold), findsOneWidget);
    });

    testWidgets('Preserves reference number across multiple rebuilds and accesses',
        (WidgetTester tester) async {
      final loanProvider = LoanProvider();
      final ref1 = loanProvider.demoReferenceNumber;

      await tester.pumpWidget(createLoanStatusApp(customLoanProvider: loanProvider));
      await tester.pumpAndSettle();

      final ref2 = loanProvider.demoReferenceNumber;
      expect(ref1, equals(ref2));
      expect(find.text(ref1), findsOneWidget);
    });
  });
}
